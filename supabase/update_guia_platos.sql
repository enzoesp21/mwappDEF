## ENTRADAS

### Rabas

**Descripción:** Aros de calamar rebozados en harina y fritos a punto justo, con salsa tártara (mayonesa, pickles, pepinillos).
**Ingredientes principales:** Calamar, harina, aceite.
**Cómo sugerirlo al cliente:** Entrada clásica para compartir.

### Langostinos Empanados

**Descripción:** Langostinos marinados y empanados en pan rallado. Acompañados con ½ porción de papas fritas.
**Ingredientes principales:** Langostinos, huevo, condimentos (provenzal, ají molido y orégano), pan rallado.
**Cómo sugerirlo al cliente:** 10 langostinos acompañados con ½ porción de papas fritas. Una entrada contundente.

### Gambas al Ajillo
`SIN TACC`

**Descripción:** Gambas salteadas con ajo, vino blanco y especias (pimentón, ½ cucharada de ají molido, pimienta y sal). Acompañadas con papas españolas.
**Ingredientes principales:** Gambas, ajo, vino blanco, caldo de pescado, manteca.
**Cómo sugerirlo al cliente:** Gambas a base de ajo, aceite de oliva, pimentón, vino blanco y papas españolas.

### Tabla de Mar

**Descripción:** Rabas, calamarettes, cornalitos, pesca blanca y langostinos rebozados en harina y fritos.
**Ingredientes principales:** Rabas, cornalitos, calamaretes, pesca blanca, langostinos, harina.
**Cómo sugerirlo al cliente:** Para compartir como entrada, de 2 a 4 personas. Ideal para acompañar con una ensalada de hojas verdes como la ensalada Mirador, o una porción de papas fritas.

### Tortilla de Papa
`SIN TACC` `VEGETARIANO`

**Descripción:** Clásica tortilla con papas, cebolla y morrón.
**Ingredientes principales:** Papas, cebolla, morrón, huevos, sal, pimienta.
**Cómo sugerirlo al cliente:** Clásica tortilla a base de papas, huevo, cebolla, sal y pimienta.

### Burrata
`SIN TACC` `VEGETARIANO`

**Descripción:** Burrata sobre colchón de rúcula acompañada de tomates cherry, tomates confitados y frutos secos.
**Ingredientes principales:** Ya mencionados.
**Cómo sugerirlo al cliente:** Queso de origen italiano elaborado a base de leche de vaca, con un interior de crema e hilos de mozzarella, acompañado de hojas verdes, tomates cherry, tomates confitados y frutos secos. Ideal como entrada para 2 personas.

