## PESCADOS

### Cazuela de Mariscos
`SIN TACC`

**Descripción:** Cazuela con langostinos, mariscos y salsa de mar.
**Ingredientes principales:** Langostinos, vieyras, cayo de vieyras, mejillones, tentáculo de calamar, aleta de calamar, salsa pomodoro, vino blanco, aceite de oliva, perejil.
**Cómo sugerirlo al cliente:** Es una cazuela con langostinos, callo de vieira, mejillones, aleta y tentáculo de calamar, todo salteado en fumet de pescado (caldo de pescado), vino blanco y manteca.

### Abadejo a la Crema de Limón
`SIN TACC`

**Descripción:** Abadejo con salsa cremosa de limón y cúrcuma.
**Ingredientes principales:** Abadejo, crema de leche, limón, cúrcuma.
**Salsa:** Crema de leche, jugo de limón, ½ cucharada de cúrcuma, sal y pimienta. Luego del hervor se suma maicena para lograr una salsa más espesa.
**Guarnición:** Puré duquesa (puré de papas tradicional mezclado con 2 yemas de huevo y queso rallado para gratinarlo).
**Cómo sugerirlo al cliente:** Pescado de carne blanca, con pocas espinas y muy liviano, con salsa a base de crema de leche, cúrcuma y jugo de limón, acompañado de puré duquesa.

### Abadejo Grillé
`SIN TACC`

**Descripción:** El abadejo es un pescado de mar que se encuentra en aguas frías, especialmente frente a las costas argentinas y uruguayas. Es una especie muy apreciada por su carne blanca, firme y delicada, con un sabor suave que lo hace ideal para preparaciones simples como a la plancha o con salsas livianas. Se destaca por tener pocas espinas, lo que lo convierte en una opción cómoda y segura para todo tipo de comensales, incluso quienes no suelen pedir pescado.
**Ingredientes principales:** Abadejo, aceite de oliva y limón, con vegetales grillé (zanahoria, zucchini, cebolla, morrón).
**Cómo sugerirlo al cliente:** Es un pescado de carne blanca, con pocas espinas y muy liviano. Ideal para acompañar con vegetales salteados o salsas sin tanto volumen.

### Trucha a la Manteca con Alcaparras
`SIN TACC`

**Descripción:** Pez de agua dulce de la Patagonia Argentina, de carne suave y sabrosa ya que tiene alto contenido graso. Servido con vegetales y salsa de manteca, limón y alcaparras.
**Ingredientes principales:** Trucha, manteca, alcaparras, jugo de limón.
**Cómo sugerirlo al cliente:** Pescado suave, de alto contenido graso, a la manteca con alcaparras y jugo de limón, acompañado de vegetales.

### Salmón Rosado a la Crema de Camarones
`SIN TACC`

**Descripción:** El salmón rosado es un pescado de carne firme, grasa y muy sabrosa, con una textura suave y mantecosa que se deshace en la boca. Se cocina a la plancha para conservar su jugosidad natural y se acompaña con una salsa cremosa de camarones salteados con cebolla, crema de leche y queso rallado gratinado, que realza su sabor sin opacarlo.
**Ingredientes principales:** Salmón, camarones, crema de leche, cebolla, queso rallado.
**Salsa:** Gambas salteadas con cebolla, crema de leche y queso rallado, por último para gratinar.
**Cómo sugerirlo al cliente:** Es un pescado de carne firme, de alto contenido graso y muy sabrosa, con una salsa de camarones a base de crema de leche y acompañado de puré duquesa.

### Chernia Grillé
`SIN TACC`

**Descripción:** La chernia es un pez de mar que habita en aguas profundas y frías del Atlántico Sur. Es muy apreciada por su carne blanca, firme y de sabor suave, que la convierte en una excelente opción para quienes buscan un pescado sabroso pero no invasivo. Se cocina a la plancha con aceite de oliva para conservar su textura natural y su jugosidad, y se acompaña con vegetales grillé como zanahoria, zucchini, cebolla y morrón.
**Ingredientes principales:** Chernia, aceite de oliva, vegetales grillé (zanahoria, zucchini, cebolla, morrón).
**Cómo sugerirlo al cliente:** Un pescado de carne blanca, firme, con sabor delicado y muy pocas espinas. Ideal para quienes prefieren preparaciones livianas y saludables, acompañado de vegetales grillados.

### Chernia con Salsa Mar del Plata
`SIN TACC`

**Descripción:** Chernia a la plancha acompañada con una generosa salsa de mariscos, manteca y vino blanco. Es un pescado de textura firme y sabor suave, ideal para combinar con sabores intensos del mar. La salsa incluye un salteado de cebolla, vieiras, callo de vieiras, gambas y mejillones, ligado con manteca y demi-glace, creando un equilibrio perfecto entre lo cremoso y lo marino. Se sirve con papas rústicas como guarnición.
**Ingredientes principales:** Chernia, cebolla, vieiras, callo de vieiras, gambas, mejillones, manteca, vino blanco, salsa demi-glace, papas rústicas.
**Cómo sugerirlo al cliente:** Chernia grillada de sabor suave acompañada de una salsa abundante de mariscos salteados en manteca y vino blanco.

