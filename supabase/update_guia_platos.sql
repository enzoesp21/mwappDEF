## ARROCES

### Paella
`SIN TACC`

**Descripción:** Cazuela de arroz azafranado con pollo, mariscos y vegetales.
**Ingredientes principales:** Pollo, langostinos, mejillones, vieiras, cayo de vieiras, arroz, caldo de pescado, arvejas, cholitos o mejillones pelados y calamar.
**Cómo sugerirlo al cliente:** Es un arroz azafranado con pollo, langostinos y mariscos, todo cocinado en su propio caldo. Un plato completo, sabroso y bien tradicional.

> Es **el plato de la casa**.

### Caya Chilena
`SIN TACC`

**Descripción:** Arroz azafranado con pollo, lechuga, champiñones y jamón. Gratinado con crema y queso.
**Ingredientes principales:** Arroz azafranado, pollo, lechuga, champiñones, jamón, crema, queso.
**Cómo sugerirlo al cliente:** Arroz cremoso azafranado a base de pollo, champiñones, jamón, lechuga, crema de leche y queso gratinado. Algo sencillo pero que sin dudas no falla.

### Risotto con Frutos de Mar
`SIN TACC`

