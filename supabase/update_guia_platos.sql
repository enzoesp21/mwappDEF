## PREGUNTAS FRECUENTES

**¿Cuál es el plato de la casa?**
La **Paella**, ya que representa a la perfección la identidad del lugar: una propuesta abundante, colorida y llena de sabor, ideal para compartir.

**¿Cuándo se construyó Mirador Waikiki?**
Se inauguró en **1999**, y el salón **Ala Wai** en **2004**.

**¿Quién se encarga de la parte de eventos?**
Todos los eventos en Mirador Waikiki son realizados por la empresa **Mar Eventos**. En la recepción del restaurante se pueden encontrar las tarjetas para contactarse.

**¿Desde cuándo está el hotel?**
El **Hotel ili ili** se inauguró en **diciembre de 2023**. Es un hotel boutique con **17 habitaciones**.

**¿Cuándo se remodeló el lugar?**
Se comenzó a remodelar en **abril de 2024**. A día de hoy aún siguen en proceso ciertas remodelaciones.

**¿Cuánto tiempo se puede dejar el auto estacionado?**
El tiempo máximo de permanencia es de **2 horas habiendo consumido**. Superado ese tiempo, o sin consumo, el estacionamiento se abona.

**¿Qué es Mirador 9?**
Es un balneario y restaurante a cargo de la misma empresa que Mirador Waikiki. El restaurante abre **todos los sábados y domingos del año**, y **todos los días en meses de temporada**.

**¿Me puedo cambiar de mesa?**
"Permítame que llame a una de las chicas de recepción para que puedan reubicarlos."

**¿Se permite el ingreso de animales?**
Si bien no somos pet-friendly, se permite la estadía de animales en el **sector del balcón**.

**¿El lugar cambió de firma?**
Sí, cambió de firma en **noviembre de 2023**.

**¿Se puede bajar a la playa?**
No contamos con bajada directa. Se puede acceder a la playa pública saliendo del predio y bajando por las **escaleras blancas** que están a pocos metros de la salida del complejo. Tené en cuenta que el estacionamiento gratuito es válido únicamente durante la estadía en el restaurante, no durante el tiempo en la playa.

