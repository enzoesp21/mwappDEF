## GLOSARIO DE COCINA

### Salsa Demi-Glace

Reducción de caldo de carne con verduras y vino, cocinada lentamente hasta lograr una salsa espesa, oscura y muy sabrosa. Ideal para acompañar carnes y pescados.

### Caldo de Pescado (Fumet)

Se hierven en cocción lenta recortes de langostinos, piel de pescado, cabeza de pescado y vegetales, hasta lograr un caldo intenso y lleno de sabor.

### Puré Duquesa

Puré de papas tradicional mezclado con dos yemas de huevo y queso rallado, para gratinarlo.

