## PRESENTACIÓN

Bienvenidos a todos los lectores a la **Guía de Platos e Ingredientes 2025**. Este documento está diseñado para que puedan conocer el detalle de cada plato de nuestro menú, con descripciones claras y sencillas.

Van a encontrar **ingredientes principales, acompañamientos y sugerencias** para ofrecerlos con seguridad y profesionalismo.

> Nuestro objetivo es que todos conozcan las preparaciones e ideas de nuestros platos, para brindar mejor asesoramiento a los clientes y nutrir sus propios conocimientos.

---

## CÓMO LEER ESTA GUÍA

A lo largo de la guía vas a encontrar estas etiquetas debajo del nombre del plato:

| Etiqueta | Significa |
|---|---|
| `SIN TACC` | Se puede pedir sin TACC |
| `VEGETARIANO` | Se puede pedir apto vegetariano |
| `VEGANO` | Se puede pedir apto vegano |

> **Importante:** si un plato no tiene etiqueta, no lo ofrezcas como apto. Ante la duda, consultá con cocina antes de confirmarle algo al cliente.

