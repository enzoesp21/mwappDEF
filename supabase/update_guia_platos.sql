## CARNES — CORTES DE CERDO

### Bondiola

**Descripción:** Corte del cerdo que se extrae de la parte superior del cuello. Es una carne muy sabrosa, ligeramente infiltrada de grasa, lo que la hace jugosa y tierna al cocinarla. Ideal para cocciones lentas, a la parrilla o a la plancha, donde se realzan sus sabores intensos.

### Solomillo

**Descripción:** Es el corte más tierno del cerdo, ubicado junto al lomo. De textura suave y sabor delicado, se cocina rápidamente y no requiere cocciones prolongadas. Es perfecto para preparaciones a la plancha, al horno o con salsas suaves que no opaquen su sabor.

